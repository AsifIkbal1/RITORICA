import { recordHitFn } from "@/lib/visitor-tracker.functions";
import { useAuth } from "@/lib/auth";

function VisitorTracker() {
  const router = useRouter();
  const { session, profile } = useAuth();

  useEffect(() => {
    const track = () => {
      try {
        if (typeof window === "undefined") return;
        let sid = window.sessionStorage.getItem("supportdesk_visitor_sid");
        if (!sid) {
          sid = "v_" + Math.random().toString(36).slice(2, 10);
          window.sessionStorage.setItem("supportdesk_visitor_sid", sid);
        }
        const userAgent = navigator?.userAgent || "";
        const role = profile?.roles?.[0] || "visitor";
        const userName = profile?.full_name || profile?.username || (session ? "User" : "Guest Visitor");

        void recordHitFn({
          data: {
            path: window.location.pathname,
            session_id: sid,
            user_name: userName,
            role,
            user_agent: userAgent,
          },
        });
      } catch {}
    };

    track();
    const interval = setInterval(track, 45000);
    return () => clearInterval(interval);
  }, [router.state.location.pathname, session, profile]);

  return null;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AuthProvider>
        <VisitorTracker />
        <Outlet />
        <Toaster richColors position="top-right" />
      </AuthProvider>
    </QueryClientProvider>
  );
}
