import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useEffect, useState } from "react";
import { toast } from "sonner";
import { Loader2 } from "lucide-react";
import { supabase } from "@/integrations/supabase/client";
import { PRIORITIES, friendlyError } from "@/lib/constants";
import { Guard, meta } from "@/components/guard";
import { PageHeader, TableSkeleton } from "@/components/states";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import type { Json } from "@/integrations/supabase/types";

export const Route = createFileRoute("/_app/settings")({
  head: () => meta("Settings", "System configuration."),
  component: () => <Guard perm="settings.manage"><Settings /></Guard>,
});

type V = Record<string, Json>;

function Settings() {
  const qc = useQueryClient();
  const q = useQuery({
    queryKey: ["settings"],
    queryFn: async () => {
      const { data, error } = await supabase.from("settings").select("*");
      if (error) throw error;
      return Object.fromEntries(data.map((d) => [d.key, d.value])) as V;
    },
  });
  const [v, setV] = useState<V>({});
  const [busy, setBusy] = useState(false);
  useEffect(() => { if (q.data) setV(q.data); }, [q.data]);
  if (q.isLoading) return <TableSkeleton />;
  const s = (k: string) => String(v[k] ?? "");
  const field = (k: string, label: string, hint?: string, type = "text") => (
    <div className="space-y-1.5"><Label>{label}</Label><Input type={type} value={s(k)} onChange={(e) => setV({ ...v, [k]: type === "number" ? Number(e.target.value) : e.target.value })} />{hint && <p className="text-xs text-muted-foreground">{hint}</p>}</div>
  );

  async function save() {
    setBusy(true);
    const rows = Object.entries(v).map(([key, value]) => ({ key, value, updated_at: new Date().toISOString() }));
    const { error } = await supabase.from("settings").upsert(rows);
    setBusy(false);
    if (error) return void toast.error(friendlyError(error));
    const { data: u } = await supabase.auth.getUser();
    if (u.user) await supabase.from("activity_logs").insert({ user_id: u.user.id, action: "settings.updated", entity_type: "settings", description: "System settings updated" });
    toast.success("Settings saved");
    qc.invalidateQueries({ queryKey: ["settings"] });
  }

  return (
    <div className="mx-auto max-w-3xl">
      <PageHeader title="Settings" actions={<Button onClick={save} disabled={busy}>{busy && <Loader2 className="size-4 animate-spin" />} Save settings</Button>} />
      <div className="space-y-5">
        <Card className="shadow-card"><CardHeader><CardTitle className="text-base">General</CardTitle></CardHeader>
          <CardContent className="grid gap-4 sm:grid-cols-2">
            {field("system_name", "System name")}
            {field("logo_url", "Logo URL", "https://… image shown in emails/exports")}
            {field("timezone", "Default timezone", "e.g. Asia/Dhaka")}
            {field("date_format", "Date format", "e.g. MMM d, yyyy")}
            {field("time_format", "Time format", "e.g. h:mm a or HH:mm")}
          </CardContent>
        </Card>
        <Card className="shadow-card"><CardHeader><CardTitle className="text-base">Tickets</CardTitle></CardHeader>
          <CardContent className="grid gap-4 sm:grid-cols-2">
            <div className="space-y-1.5"><Label>Default priority</Label>
              <Select value={s("default_priority") || "medium"} onValueChange={(x) => setV({ ...v, default_priority: x })}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>{PRIORITIES.map((p) => <SelectItem key={p.value} value={p.value}>{p.label}</SelectItem>)}</SelectContent>
              </Select>
            </div>
            <div className="space-y-1.5"><Label>Default status</Label><Input value="Unanswered" disabled /><p className="text-xs text-muted-foreground">New tickets always start as Unanswered.</p></div>
            <div className="space-y-1.5"><Label>Ticket ID format</Label><Input value="TKT-000001" disabled /><p className="text-xs text-muted-foreground">Generated by the database; never reused.</p></div>
            {field("max_attachment_mb", "Attachment size limit (MB)", "Storage enforces a hard 10 MB cap.", "number")}
            <div className="sm:col-span-2">{field("allowed_file_types", "Allowed file types", "Comma-separated extensions")}</div>
          </CardContent>
        </Card>
        <Card className="shadow-card"><CardHeader><CardTitle className="text-base">Notifications</CardTitle>
          <CardDescription>Email delivery is optional. In-app notifications work independently.</CardDescription></CardHeader>
          <CardContent className="space-y-3">
            <div className="flex items-center justify-between"><Label>In-app notifications</Label><Switch checked={v["notifications_enabled"] !== false} onCheckedChange={(x) => setV({ ...v, notifications_enabled: x })} /></div>
            <div className="flex items-center justify-between"><Label>Email notifications</Label><Switch checked={v["email_notifications_enabled"] === true} onCheckedChange={(x) => setV({ ...v, email_notifications_enabled: x })} /></div>
            <p className="text-xs text-muted-foreground">Email sending requires connecting an email provider; credentials are stored securely on the server and never in this page.</p>
          </CardContent>
        </Card>
        <Card className="shadow-card"><CardHeader><CardTitle className="text-base">Security</CardTitle></CardHeader>
          <CardContent className="grid gap-4 sm:grid-cols-2">
            {field("min_password_length", "Minimum password length", "Applied in sign-up and password forms", "number")}
            {field("session_timeout_hours", "Session timeout (hours)", "Informational; sessions refresh automatically", "number")}
          </CardContent>
        </Card>
      </div>
    </div>
  );
}
